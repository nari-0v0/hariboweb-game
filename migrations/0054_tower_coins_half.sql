-- 탑 층 보상 젤코인을 n개 → n의 절반(올림)으로 줄였어요(나리 2026-11-19). 이미 오른 사람은 더 받은 만큼 빼요(나리: "이미 받은사람은 조정해").
-- 1~T층에서 더 받은 양 = Σ(f − ⌈f/2⌉) = Σ⌊f/2⌋ = ⌊T²/4⌋. 이미 써서 모자라면 0까지만 빼요.
-- 이 파일은 새 보상 코드와 같이 배포돼서, 그 전에 오른 층까지 한 번에 맞춰요.
UPDATE journey_bank SET coins = MAX(0, coins - (tower * tower) / 4) WHERE tower > 0;
